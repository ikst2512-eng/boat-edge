const three=ticketClarity(ten.slice(0,3));
assert(three.top3.includes('上位3点'));
assert(three.top5.includes('未確認'));
assert(three.top10.includes('未確認'));
const bad=ticketClarity(['1-2-3','1-2-3','2-1-3']);
assert.equal(bad.head,'未確認','duplicate ticket invalidates head-and-coverage display');
const stopped=ticketClarity(ten,false);
assert.equal(stopped.head,'未確認','scratch/stop cannot render a head recommendation');
assert.equal(stopped.top10,'未確認');
