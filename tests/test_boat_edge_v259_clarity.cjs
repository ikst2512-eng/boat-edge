const source=fs.readFileSync('assets/boat_edge_v207_first_prediction.js','utf8');
const view={},document={readyState:'loading',addEventListener(){}};
vm.runInNewContext(source,{window:view,document,Number,Date,Math,Set,Map,JSON,Intl}, {filename:'V259-display-only.js'});
